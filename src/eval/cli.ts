import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { closePool } from '../memory/pool.js';
import { runEval, type EvalResult, type SystemResult } from './run.js';

const OUT_DIR = fileURLToPath(new URL('../../eval/', import.meta.url));
const OUT_PATH = `${OUT_DIR}results.md`;

async function main(): Promise<void> {
  const argv = process.argv.slice(2);
  const positives = numberArg(argv, '--positives') ?? 200;
  const negatives = numberArg(argv, '--negatives') ?? 5000;

  console.log(`Evaluating: ${positives} known positives, ${negatives} known negatives`);

  let lastStage = '';
  const result = await runEval({
    positives,
    negatives,
    onProgress: (stage, done, total) => {
      if (stage !== lastStage) {
        if (lastStage) process.stdout.write('\n');
        lastStage = stage;
      }
      if (done % 100 === 0 || done === total) {
        process.stdout.write(`\r  ${stage}: ${done}/${total}   `);
      }
    },
  });
  process.stdout.write('\n\n');

  const markdown = render(result);
  await mkdir(OUT_DIR, { recursive: true });
  await writeFile(OUT_PATH, markdown, 'utf8');

  console.log(headline(result));
  console.log(`\nWritten to eval/results.md  (${result.elapsedSeconds.toFixed(1)}s)`);
}

function numberArg(argv: string[], flag: string): number | null {
  const i = argv.indexOf(flag);
  if (i < 0) return null;
  const value = Number(argv[i + 1]);
  return Number.isFinite(value) ? value : null;
}

function pct(value: number): string {
  return `${(value * 100).toFixed(1)}%`;
}

/** The table printed to stdout and pasted into the README and Devpost. */
function headline(r: EvalResult): string {
  const b = r.baseline.operating;
  const s = r.sifta.operating;
  const reduction =
    b.falsePositives === 0
      ? 'n/a'
      : `${(((b.falsePositives - s.falsePositives) / b.falsePositives) * 100).toFixed(1)}%`;

  const rows = [
    ['', 'Jaro-Winkler baseline', 'Sifta'],
    [`Recall (of ${r.positives} known hits)`, pct(b.recall), pct(s.recall)],
    ['Missed hits', String(b.falseNegatives), String(s.falseNegatives)],
    [`False positives (of ${r.negatives})`, String(b.falsePositives), String(s.falsePositives)],
    ['Precision', pct(b.precision), pct(s.precision)],
    ['Operating threshold', b.threshold.toFixed(2), b === s ? '' : s.threshold.toFixed(2)],
  ];
  rows[5]![2] = s.threshold.toFixed(2);

  const widths = [0, 1, 2].map((col) =>
    Math.max(...rows.map((row) => row[col]!.length)),
  );
  const line = (row: string[]): string =>
    `| ${row.map((cell, i) => cell.padEnd(widths[i]!)).join(' | ')} |`;

  return [
    line(rows[0]!),
    `|${widths.map((w) => '-'.repeat(w + 2)).join('|')}|`,
    ...rows.slice(1).map(line),
    '',
    `False-positive reduction: ${reduction}`,
  ].join('\n');
}

function sweepTable(system: SystemResult, unit: string): string {
  const header = `| ${unit} | Recall | Missed | False positives | Precision |\n|---|---|---|---|---|`;
  const body = system.sweep
    .map(
      (p) =>
        `| ${p.threshold.toFixed(2)} | ${pct(p.recall)} | ${p.falseNegatives} | ${p.falsePositives} | ${pct(p.precision)} |`,
    )
    .join('\n');
  return `${header}\n${body}`;
}

function render(r: EvalResult): string {
  const b = r.baseline.operating;
  const s = r.sifta.operating;
  const reduction =
    b.falsePositives === 0
      ? 'n/a'
      : `${(((b.falsePositives - s.falsePositives) / b.falsePositives) * 100).toFixed(1)}%`;

  const breakdown = Object.entries(r.transformBreakdown)
    .sort((a, c) => c[1].total - a[1].total)
    .map(
      ([kind, v]) =>
        `| \`${kind}\` | ${v.total} | ${v.caughtByBaseline} | ${v.caughtBySifta} |`,
    )
    .join('\n');

  return `# Evaluation results

Generated by \`npm run eval\`. Reproducible: the corpora are built from
fixed-seed PRNGs and fixed SQL ordering, so two runs produce identical numbers.

## Headline

| | Jaro-Winkler baseline | Sifta |
|---|---|---|
| Recall (of ${r.positives} known hits) | ${pct(b.recall)} | ${pct(s.recall)} |
| Missed hits | ${b.falseNegatives} | ${s.falseNegatives} |
| False positives (of ${r.negatives}) | ${b.falsePositives} | ${s.falsePositives} |
| Precision | ${pct(b.precision)} | ${pct(s.precision)} |
| Operating threshold | ${b.threshold.toFixed(2)} (similarity) | ${s.threshold.toFixed(2)} (L2 distance) |

**False-positive reduction: ${reduction}**

## What was measured

| | |
|---|---|
| Watchlist entities | ${r.watchlistEntities.toLocaleString()} |
| Names available to the baseline (primary + aliases) | ${r.baselineNames.toLocaleString()} |
| Embedded variants available to Sifta | ${r.siftaVariants.toLocaleString()} |
| Known positives | ${r.positives} |
| Known negatives | ${r.negatives} |
| Negatives discarded as genuine list collisions | ${r.negativesDiscarded} |
| Runtime | ${r.elapsedSeconds.toFixed(1)}s |

## Methodology

Both systems receive **identical inputs** and are scored on identical criteria.

**The baseline is not a strawman.** It is Jaro-Winkler — the standard fuzzy
matcher in commercial sanctions screening — and it is given every advantage
that does not involve variant generation:

- It is **token-aware**, so name reordering costs it nothing. "Joshua Usifoh"
  against "Usifoh Joshua" scores 1.0.
- It sees **the full alias list OFAC publishes** (${r.baselineNames.toLocaleString()} names),
  not just primary names.
- Its threshold is **swept across the whole range** and the best operating
  point is chosen for it, exactly as for Sifta.

The only difference is what Sifta adds: generated name variants
(reordering, transliteration, traditional-name contraction, initialisation,
name-part dropping), embedded and searched by vector similarity.

**Known positives.** ${r.positives} real OFAC SDN individuals. For each, a
spelling a customer might plausibly write is produced by applying one variant
transformation **plus a single character-level typo**.

The typo is the important part. Without it the test would be circular: the
variant string would already sit verbatim in Sifta's index, and the test would
prove only that the pipeline is self-consistent. With it, **the test string
appears verbatim in neither system's index** — Sifta must generalise from a
near neighbour, and the baseline must absorb the same noise.

**Known negatives.** ${r.negatives} synthetic Nigerian names built
combinatorially from \`data/nigerian-names.json\` (common Yoruba, Igbo and
Hausa given names and surnames). Every generated name is cross-checked against
the ingested watchlist and discarded if it genuinely collides;
${r.negativesDiscarded} were discarded on this run. A false positive here is
therefore the matcher's noise, not a real hit mislabelled.

**Operating point.** For each system, the threshold reported is the one
producing the fewest false positives among those achieving recall ≥ 95%. If no
threshold reaches 95%, the highest-recall threshold is reported instead — the
number is never quietly adjusted to make the target appear met.

## Recall by transformation

Which kinds of name variation each system survives, at the operating points above.

| Variant rule | Positives | Caught by baseline | Caught by Sifta |
|---|---|---|---|
${breakdown}

## Full threshold sweep — baseline

Higher similarity = stricter.

${sweepTable(r.baseline, 'Similarity')}

## Full threshold sweep — Sifta

Lower L2 distance = stricter.

${sweepTable(r.sifta, 'Distance')}

## Honest limitations

- Embeddings here come from the deterministic trigram provider, not Bedrock
  Titan. It is a real lexical embedder, not noise, but a production Titan run
  would shift these numbers.
- The negative set is synthetic. It is built from a documented corpus of
  population-typical names, but it is not a real customer file. The measurement
  that would settle the question is a design partner's actual name file, which
  is exactly what the free-tier wedge in the PRD is for.
- Both systems are evaluated on individuals. Corporate and vessel matching is
  out of scope (PRD §9).
`;
}

main()
  .then(() => closePool())
  .catch(async (err: Error) => {
    console.error(`\neval failed: ${err.message}`);
    await closePool();
    process.exit(1);
  });
